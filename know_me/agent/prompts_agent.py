_WEAKNESS_VERBATIM_START = "我的缺点是，在技术方案"
_WEAKNESS_VERBATIM_END = "不再纠结细节。"
_SLIM_CORE_MAX_CHARS = 9200


def _shrink_core_for_context_budget(core: str, max_chars: int = _SLIM_CORE_MAX_CHARS) -> str:
    """精简模式下压缩产品指令体积，但保留缺点定稿原文块。"""
    if len(core) <= max_chars:
        return core
    start = core.find(_WEAKNESS_VERBATIM_START)
    end = core.find(_WEAKNESS_VERBATIM_END, start if start >= 0 else 0)
    if start < 0 or end < 0:
        return core[:max_chars].rstrip() + "…"
    end += len(_WEAKNESS_VERBATIM_END)
    weakness = core[start:end]
    head_budget = max(2000, max_chars - len(weakness) - 48)
    head = core[:head_budget].rstrip() + "\n\n（…上文细则从简以适配上下文；缺缺点/岗位/薪酬等仍以检索语料为准。）\n\n"
    return head + weakness

