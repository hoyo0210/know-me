_PERSONA_SECTION_INTRO = """---
### 求职者个性化人设（persona）

以下内容来自求职者本人配置的 Markdown（`IDENTITY.md` 正文与 `SOUL.md`），**不是** Know Me 产品默认系统提示词；用于个人叙事、口吻与自我约束。若与本消息更上方的 **Know Me 产品侧系统指令** 冲突，**以上方产品指令为准**。

---
"""


def _append_persona(core: str, *, persona_max_chars: int | None) -> str:
    p = get_persona()
    persona_body = "\n\n".join(x for x in (p.identity_body, p.soul_body) if x.strip())
    if not persona_body.strip():
        return core
    if persona_max_chars is not None and len(persona_body) > persona_max_chars:
        persona_body = persona_body[:persona_max_chars].rstrip() + "…"
    return core + "\n\n" + _PERSONA_SECTION_INTRO.strip() + "\n\n" + persona_body.strip()


def _build_agent_system_prompt(*, slim: bool = False) -> str:
    p = get_persona()
    owner = p.display_name
    core = _KNOW_ME_CORE_INSTRUCTIONS.replace("{owner_name}", owner)
    if slim:
        core = _shrink_core_for_context_budget(core)
        core = core + "\n\n" + _SLIM_RECRUITMENT_PHASES
        return _append_persona(core, persona_max_chars=1200)
    core = core + _KNOW_ME_FEWSHOT_BLOCK
    core = core + "\n\n" + _RECRUITMENT_CONVERSATION_PHASES.replace("{owner_name}", owner)
    return _append_persona(core, persona_max_chars=None)


def get_agent_system_prompt(*, slim: bool = False) -> str:
    """拼装 Agent system。`slim=True` 时省略 few-shot 与长篇阶段说明，用于上下文预算紧张时。"""
    return _build_agent_system_prompt(slim=slim)


